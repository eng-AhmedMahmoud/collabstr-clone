export type Locale = "en" | "ar";
export const DEFAULT_LOCALE: Locale = "en";

export async function getLocale(): Promise<Locale> {
  const v = (await cookies()).get("locale")?.value;
  return v === "ar" ? "ar" : "en";
}

export function dirOf(l: Locale): "ltr" | "rtl" {
  return l === "ar" ? "rtl" : "ltr";
}

